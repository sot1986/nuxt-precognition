import { addImports, addPlugin, addServerImports, addNitroPlugin, createResolver, defineNuxtModule, addTypeTemplate, hasNuxtCompatibility } from '@nuxt/kit'
import defu from 'defu'
import type { Config } from './runtime/types/config'

// Module options TypeScript interface definition
export interface ModuleOptions extends Config {}

export default defineNuxtModule<ModuleOptions>({
  meta: {
    name: 'nuxt-precognition',
    configKey: 'precognition',
    compatibility: {
      nuxt: '>=3.9.0',
    },
  },
  // Default configuration options of the Nuxt module
  defaults: {
    validationTimeout: 1500,
    backendValidation: false,
    validateFiles: false,
    enableNuxtClientErrorParser: false,
    enableLaravelClientErrorParser: false,
    enableLaravelServerErrorParser: false,
  },
  async setup(options, nuxt) {
    nuxt.options.runtimeConfig.public.precognition = defu(
      nuxt.options.runtimeConfig.public.precognition as Partial<ModuleOptions>,
      {
        validationTimeout: options.validationTimeout,
        backendValidation: options.backendValidation,
        validateFiles: options.validateFiles,
        enableNuxtClientErrorParser: options.enableNuxtClientErrorParser,
        enableLaravelClientErrorParser: options.enableLaravelClientErrorParser,
        enableLaravelServerErrorParser: options.enableLaravelServerErrorParser,
      },
    )

    const resolver = createResolver(import.meta.url)

    // Do not add the extension since the `.ts` will be transpiled to `.mjs` after `npm run prepack`
    addPlugin(resolver.resolve('./runtime/plugin'))

    addImports({
      name: 'useForm',
      from: resolver.resolve('./runtime/useForm'),
      as: 'useForm',
    })

    // Server compatibility (Nuxt 4.6+): Nuxt picks the variant the configured server builder can run.
    // - `nuxt`: portable implementation based on `nuxt/server` (Nitro v3 / Nuxt 5 and other server builders)
    // - `nitro2`: h3 v1 implementation for hosts running `nitropack` v2 (Nuxt 3 and 4)
    addServerImports([
      {
        from: {
          nuxt: resolver.resolve('./runtime/server/definePrecognitiveEventHandler'),
          nitro2: resolver.resolve('./runtime/server/definePrecognitiveEventHandler-legacy'),
        },
        name: 'definePrecognitiveEventHandler',
      },
    ])

    // The plugin doesn't import any server runtime, so it runs as-is on both Nitro majors.
    // Skip registering it on non-Nitro server builders (e.g. `@nuxt/vite-server`) to avoid
    // NUXT_B8024 warnings; the portable handler lazily initializes `event.context.$precognition`.
    const serverBuilder = nuxt.options.server?.builder
    const isNitroBuilder = serverBuilder === undefined
      || serverBuilder === 'nitro'
      || (typeof serverBuilder === 'string' && /(?:^|[\\/])(?:@nuxt\/)?nitro-server(?:$|[\\/.])/.test(serverBuilder))

    if (isNitroBuilder) {
      const serverPlugin = resolver.resolve('./runtime/server/plugin')
      addNitroPlugin({
        nitro2: serverPlugin,
        nitro3: serverPlugin,
      })
    }

    const supportsNuxtServer = await hasNuxtCompatibility({ nuxt: '>=4.6.0-0' }, nuxt)

    addTypeTemplate({
      filename: 'types/nuxt-precognition.d.ts',
      getContents: () => `// Generated by nuxt-precognition
import type {ValidationErrorParser, ValidationErrorsData} from '${resolver.resolve('./runtime/types/core')}'
import type {ClientStatusHandlers} from '${resolver.resolve('./runtime/types/form')}'

interface NuxtPrecognition {
  $precognition: {
    errorParsers: ValidationErrorParser[],
    statusHandlers: ClientStatusHandlers,
    assertSuccessfulPrecognitiveResponses: (ctx: { options: { headers?: HeadersInit }, response: Response }) => void
  }
}

declare module '#app' {
  interface NuxtApp extends NuxtPrecognition {}
}

declare module 'vue' {
  interface ComponentCustomProperties extends NuxtPrecognition {}
}

export {
  ValidationErrorParser,
  ClientStatusHandlers,
  ValidationErrorsData
}`,
    })

    addTypeTemplate({
      filename: 'types/nuxt-precognition-server.d.ts',
      getContents: () => {
        const lines = [
          '// Generated by nuxt-precognition',
          `import type { PrecognitionEventContext } from '${resolver.resolve('./runtime/types/eventHandler')}'`,
        ]

        if (isNitroBuilder) {
          lines.push(
            `import type { H3Event } from 'h3'`,
            `declare module 'h3' {`,
            `  interface H3EventContext extends PrecognitionEventContext<H3Event> {}`,
            `}`,
          )
        }

        if (supportsNuxtServer) {
          lines.push(
            `import type { RequestEvent } from 'nuxt/server'`,
            `declare module 'nuxt/schema' {`,
            `  interface RequestEventContext extends PrecognitionEventContext<RequestEvent> {}`,
            `}`,
          )
        }

        lines.push('export {}')
        return lines.join('\n')
      },
    }, { nitro: true, nuxt: false })
  },
})
